static uint32_t MQ_Promedio(uint8_t n)
{
    uint32_t suma = 0;
    for (uint8_t i = 0; i < n; i++) {
        adc_value = ADC_Read(&hadc1);
        suma += adc_value;
        HAL_Delay(20);
    }
    return suma / n;
}
 
static void mq135_task(void)
{
    static uint32_t t_muestra = 0;
    static uint32_t suma = 0;
    static uint8_t  n = 0;
 
    if ((HAL_GetTick() - t_muestra) < MQ_PERIODO_MUESTRA_MS) return;
    t_muestra = HAL_GetTick();
 
    adc_value = ADC_Read(&hadc1);
    suma += adc_value;
 
    if (++n >= MQ_MUESTRAS) {
        co2_ppm = MQ135_ReadPPM(&sensor_mq135, suma / MQ_MUESTRAS);
        suma = 0;
        n = 0;
    }
}
